/* 오늘이 며칠인가 — 도구들이 한 벌로 쓰는 자
 *
 * 왜 따로 두는가:
 *   `new Date().toISOString().slice(0, 10)` 은 **UTC 날짜**를 준다. 이 집을
 *   짓는 사람은 한국(UTC+9)에 있으므로, **한국 시간 00:00~09:00 사이에
 *   도구를 돌리면 어제 날짜가 박힌다** — 하루의 아홉 시간, 37.5% 다.
 *   2026-09-04 에 재어 보니 네 도구가 모두 그 자를 쓰고 있었다.
 *
 *   갈무리에 「9.3 기준」이라 적혀 있는데 실은 9월 4일에 구운 것이라면,
 *   그 갈무리는 자기가 언제 것인지를 틀리게 말하는 셈이다. 갈무리의 뜻이
 *   「언제 것인지 밝힌다」에 있으니 이 하루가 그냥 넘길 일이 아니다.
 *
 *   달(snapshot-now)은 더 나쁘다. 매달 1일 새벽에 갈무리하면 **지난달**
 *   파일로 저장되어, 이미 있는 갈무리를 덮어쓸 뻔한다.
 *
 * 무엇이 중요한가:
 *   **도구를 돌리는 사람의 달력을 따른다.** 화면에 「9.4 기준」이라 적힐
 *   때 그 9월 4일은 보는 사람의 9월 4일이어야지 그리니치의 것이 아니다.
 */

/* 로컬 시간대의 달력 날짜 — YYYY-MM-DD */
export const 오늘 = () => 자르기(10);

/* 로컬 시간대의 달 — YYYY-MM */
export const 이달 = () => 자르기(7);

function 자르기(n) {
  const d = new Date();
  /* 시간대만큼 밀어 두면 toISOString 이 로컬 달력을 읽어 준다 */
  return new Date(d.getTime() - d.getTimezoneOffset() * 60000)
    .toISOString().slice(0, n);
}
